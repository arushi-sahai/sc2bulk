"""The pooled minimum-detectable-difference rows at K = 3 and K = 2 over the whole rho x A grid, with the all-pairs row for reference: every K-subset of the pairs mdd_table.py pools, so no pair is singled out.
Each row is statistics.mdd_table's pooled row for that subset, called as scripts/mdd_table.py calls it (frozen,
not edited), plus the joint intersection-union lower bound P^m for m = 5 and m = 9 (the upper bound is P).

  python scripts/mdd_subsets.py OUTDIR PAIR [PAIR ...]
The command used:
  python scripts/mdd_subsets.py OUTDIR tms soundlife pineda lupus crohns
"""
import itertools
import sys
from pathlib import Path

import pandas as pd

from sc2bulk import statistics
from sc2bulk.config import settings
from sc2bulk.config import statistics as S

JOINT_M = (5, 9)   # configurations at delta = 0


def subset_rows(pairs, k):
    """The pooled rows of every k-subset of pairs, over the grid."""
    tables = []
    for subset in itertools.combinations(pairs, k):
        t = statistics.mdd_table({p: S.CLASS_COUNTS[p] for p in subset}, S.SEED_SD, settings.N_ENCODER_SEEDS, S.MARGIN, S.ALPHA)
        t = t[t["pair"] == f"pooled K={k}"].drop(columns="pair")
        tables.append(t.assign(k=k, pairs=" ".join(subset)))
    rows = pd.concat(tables, ignore_index=True)
    for m in JOINT_M:
        rows[f"joint_lower_m{m}"] = rows["p_within_margin_at_zero"] ** m
    return rows[["k", "pairs", "rho", "auroc", "mdd", "mdd_holm_first_step", "p_within_margin_at_zero",
                 *[f"joint_lower_m{m}" for m in JOINT_M]]]


def summary(rows):
    """Markdown: per K and grid cell, min / median / max over subsets."""
    columns = {"mdd": "MDD", "p_within_margin_at_zero": "P(u < X \\| Δ = 0)",
               **{f"joint_lower_m{m}": f"joint lower, m = {m}" for m in JOINT_M}}
    lines = ["# Pooled MDD at K = all, 3 and 2, every subset (min / median / max over subsets)", "",
             "X = 0.05; joint bound under Δ = 0 for m configurations: [P^m, P] (frozen §61). "
             "Generated by scripts/mdd_subsets.py. The all-pairs row (K = all, one subset) reproduces mdd_table.csv's pooled row. "
             "Values are rounded to 3 decimals from the unrounded CSV, so they can differ in the third decimal from tables "
             "built on rounded per-pair MDDs (the smallest K = 2 MDD is 0.0565, shown 0.057; §61 printed 0.056).", "",
             "| K | subsets | ρ | A | " + " | ".join(columns.values()) + " |",
             "|---|---:|---:|---:|" + "---:|" * len(columns)]
    for (k, rho, auroc), g in rows.groupby(["k", "rho", "auroc"], sort=False):
        cells = [f"{g[c].min():.3f} / {g[c].median():.3f} / {g[c].max():.3f}" for c in columns]
        lines.append(f"| {k} | {len(g)} | {rho} | {auroc} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    out, pairs = Path(sys.argv[1]), sys.argv[2:]
    assert S.CLASS_COUNTS is not None, "pin config.statistics.CLASS_COUNTS from the blinded run first"
    assert len(pairs) > 3, "the all-pairs row and K = 3 need at least 4 pairs"
    rows = pd.concat([subset_rows(pairs, len(pairs)), subset_rows(pairs, 3), subset_rows(pairs, 2)], ignore_index=True)
    rows.to_csv(out / "mdd_subsets.csv", index=False, float_format="%.4f")
    (out / "mdd_subsets.md").write_text(summary(rows))
